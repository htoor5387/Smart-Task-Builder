//React component for the home page of the Digital Sidekick app

// This is a client component ->used for interactivity and state management in Next.js 13+ with the App Router.
//  It will be rendered on the client side and can use hooks like useState, useEffect, etc.
"use client";
import { useState } from "react";

import Image from "next/image";

export default function Home() {
 //state variable to hold the user's input/goal
  const [goal, setGoal] = useState("");
  const [activeGoal, setActiveGoal] = useState(null);
  
  //state variables to hold the AI response, loading state, and error state
  const [aiMessage, setAiMessage] = useState(""); 
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");

  //array to hold the tasks generated by the AI
  const [tasks, setTasks] = useState([]);

  // Function that sets active goal, generates a response from the AI, and handles loading and error states
  async function handleStart() {
    setActiveGoal(goal);
    setLoading(true);
    setError("");
    setAiMessage("");
    
    //sends a goal,fetches the AI response 
    try{
      //fetch the AI response from the /api/goals route
      const response = await fetch("/api/goals", {
        method: "POST", //establishes a POST request to the /api/goals route to send info
        headers: {"Content-Type": "application/json",}, //sets the type of incoming data to JSON
        body: JSON.stringify({ goal }) //convert javascript object to JSON string to send
    });
      if (!response.ok) {
        throw new Error("Failed to fetch AI response");
      }

      const data = await response.json();//parses the response as JSON
      setTasks(data.tasks); //sets the tasks in state
      //setAiMessage(data.message);//sets the AI response in state
    } catch (error) {
      setError("Failed to fetch AI response");
    } finally {
      setLoading(false);//sets loading state to false after the request is complete
    }

  }

  return (
  
<main className="min-h-screen bg-slate-950 text-white p-8">
      <div className="max-w-xl mx-auto space-y-4">
        <h1 className="text-4xl font-bold">Smart Task Builder</h1>

        <p> Have a goal or project you need done? 
          Break it down into small actional steps using the SMART framework
          ,and level up as you complete them!</p>

        <input
          className="w-full p-3 bg-slate-800 rounded-lg"
          placeholder="What is your goal?"
          value={goal}
          onChange={(event) => setGoal(event.target.value)}
        />

        <button
          onClick={handleStart}
          disabled={loading || !goal.trim()} //Prevents handleStart func from running if loading or goal is empty
          className="bg-indigo-500 px-5 py-3 rounded-lg"
        >
          Start woking on your goal
        </button>

        {activeGoal && (
            <div className="bg-slate-800 p-4 rounded-xl text-xl font-bold">
              Your Goal: {activeGoal}
            </div>
        )}
        
        {loading && (<p>Loading AI response...</p>)}
        {error && (<p className="text-red-500">{error}</p>)}
        {aiMessage && (<p className="text-green-500"> Gemini says: {aiMessage}</p>)}
        {tasks.map((task, index) => (
          <div key={index} className="bg-slate-800 p-4 rounded-xl">
            <p>Objective {index +1}:</p>
            <p>{task}</p>
          </div>
        ))}  
          
          
      </div>
    </main>
  );
}